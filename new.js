// ***** PREFIX AND POSTFIX *****

// Prefix and Postfix Operators in JavaScript

// Prefix Operator (++a)
// The operator comes BEFORE the variable.
// First, the value is increased, then it is used.

let a = 5;
let b = ++a;

console.log(a); // 6
console.log(b); // 6


// Postfix Operator (a++)
// The operator comes AFTER the variable.
// First, the value is used, then it is increased.

let x = 5;
let y = x++;

console.log(x); // 6
console.log(y); // 5


// Simple Difference

// Prefix:  ++a  → Increase first → Use
// Postfix: a++  → Use first → Increase


// Prefix decrement (--a)
let p = 5;
let q = --p;

console.log(p); // 4
console.log(q); // 4


// Postfix decrement (a--)
let m = 5;
let n = m--;

console.log(m); // 4
console.log(n); // 5
// JavaScript Variables: let, const, var

// const → value cannot be reassigned
const name = "Bulbul";
const country = "India";

// let → value can be changed
let age = 22;
age = 23;

// var → old way, generally avoid using it
var score = 100;
score = 200;

// Direct assignment → DON'T do this
// accountId = 2;

// Rule:
// const → use by default
// let   → use when the value needs to change
// var   → avoid in modern JavaScript